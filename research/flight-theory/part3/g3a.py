ax2.plot(V,q(V)*S*CL_MAX/W,color=BLUE,lw=3);ax2.text(162,q(160)*S*CL_MAX/W,"실속 반영\n(C_L 최대 1.17)",color=BLUE,fontsize=11,fontweight="bold",va="center")
ax2.axhline(1,color="#bbb",lw=1,ls=(0,(4,3)));ax2.text(158,0.45,"1G = 겨우 떠 있는 선",fontsize=10,color="#777",ha="right")
vs=np.sqrt(2*W/(rho*S*CL_MAX));ax2.axvline(vs,color=BLUE,lw=1,alpha=0.5);ax2.text(vs+1.5,13.5,f"실속 속도 {vs:.0f} m/s",fontsize=10.5,color=BLUE)
for v in [100]:
    ax2.plot(v,q(v)*S*CLA*np.radians(40)/W,"o",color=RED);ax2.plot(v,q(v)*S*CL_MAX/W,"o",color=BLUE)
    ax2.annotate("6.5G",(v,q(v)*S*CLA*np.radians(40)/W),(v-12,q(v)*S*CLA*np.radians(40)/W+0.9),fontsize=11,color=RED,fontweight="bold")
    ax2.annotate("2.3G",(v,q(v)*S*CL_MAX/W),(v+3,q(v)*S*CL_MAX/W-1.6),fontsize=11,color=BLUE,fontweight="bold")
ax2.set_xlim(40,160);ax2.set_ylim(0,15);ax2.set_xlabel("속도 (m/s)",color="#444");ax2.set_ylabel("최대로 낼 수 있는 G",color="#444");ax2.grid(axis="y",color="#eee")
fig.text(0.7,0.93,"느릴수록 실속이 선회를 막아야 한다",ha="center",fontsize=16,fontweight="bold")
fig.text(0.7,0.875,"같은 100 m/s에서 직선 모델은 실제 한계의 약 3배로 돈다",ha="center",fontsize=11,color="#555")
fig.savefig("fig/01_no_stall_problem.png",facecolor="white");plt.close(fig);trim("fig/01_no_stall_problem.png")

