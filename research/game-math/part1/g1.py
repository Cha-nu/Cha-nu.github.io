# 01 y-up vs y-down ---------------------------------------------------------
fig, axs = plt.subplots(1, 2, figsize=(10, 4.6), dpi=150)
for ax, ydown, name, sub in [(axs[0], False, "수학 좌표계 (y-up)", "위로 갈수록 y 증가 · 물리, 3D 엔진"),
                             (axs[1], True, "화면 좌표계 (y-down)", "아래로 갈수록 y 증가 · 2D 화면, UI, 웹 캔버스")]:
    grid(ax, (0, 5), (0, 4), ydown=ydown)
